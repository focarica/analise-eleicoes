CREATE OR REPLACE FUNCTION stg_tse.texto_publicado(valor text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN upper(trim(valor)) IN
        ('', '#NULO', '#NE', '-1', '-3', '-4', 'NÃO DIVULGÁVEL')
        THEN NULL ELSE trim(valor) END
$$;
CREATE OR REPLACE FUNCTION stg_tse.inteiro_nao_negativo(valor text)
RETURNS bigint LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF trim(valor) !~ '^[0-9]+$' THEN RETURN NULL; END IF;
    RETURN trim(valor)::bigint;
EXCEPTION WHEN numeric_value_out_of_range OR invalid_text_representation THEN
    RETURN NULL;
END;
$$;

-- Maior turno com situação informada e não transitória. Se nenhuma situação
-- terminal existe, turno e resultado ficam NULL. Arquivo não decide o turno.
ALTER TABLE stg_tse.candidatura ADD COLUMN IF NOT EXISTS nr_titulo_eleitoral_candidato text;
DROP VIEW IF EXISTS stg_tse.candidatura_resultado;
CREATE OR REPLACE VIEW stg_tse.candidatura_resultado AS
WITH base AS (
    SELECT s.*,
           stg_tse.inteiro_nao_negativo(ano_eleicao) AS ano_id,
           stg_tse.inteiro_nao_negativo(sq_candidato) AS candidato_id,
           CASE WHEN stg_tse.inteiro_nao_negativo(nr_turno) IN (1, 2)
                AND stg_tse.texto_publicado(ds_sit_tot_turno) IS NOT NULL
                AND upper(trim(ds_sit_tot_turno)) NOT IN
                    ('2º TURNO', '2° TURNO', '2 TURNO', 'SEGUNDO TURNO')
                THEN stg_tse.inteiro_nao_negativo(nr_turno) END AS turno_resultado,
           stg_tse.texto_publicado(ds_sit_tot_turno) AS situacao_informada
    FROM stg_tse.candidatura s
    WHERE upper(trim(s.sg_uf)) IN (SELECT sg_uf::text FROM stg_tse.escopo_uf)
       OR upper(trim(s.sg_uf)) = 'BR'
), prioridade AS (
    SELECT b.*, dense_rank() OVER (
        PARTITION BY ano_id, candidato_id
        ORDER BY turno_resultado DESC NULLS LAST
    ) AS prioridade_resultado
    FROM base b WHERE ano_id IS NOT NULL AND candidato_id IS NOT NULL
)
SELECT * FROM prioridade WHERE prioridade_resultado = 1;

-- Mantém todas as votações de origem; ausência de complemento é INDEFINIDO.
-- Não associar o complemento ao ano/SQ ignorando CD_ELEICAO.
CREATE OR REPLACE VIEW stg_tse.votacao_candidato_com_destinacao AS
SELECT v.*, d.nm_tipo_destinacao_votos,
       CASE WHEN upper(d.nm_tipo_destinacao_votos) IN ('VÁLIDO', 'VALIDO')
                 THEN 'VALIDO'
            WHEN d.nm_tipo_destinacao_votos IS NULL THEN 'INDEFINIDO'
            ELSE 'OUTRA_DESTINACAO' END AS universo_destinacao
FROM stg_tse.votacao_candidato_munzona v
LEFT JOIN stg_tse.destinacao_votos d
  ON d.ano_eleicao = stg_tse.inteiro_nao_negativo(v.ano_eleicao)
 AND d.cd_eleicao = stg_tse.inteiro_nao_negativo(v.cd_eleicao)
 AND d.sq_candidato = stg_tse.inteiro_nao_negativo(v.sq_candidato);
CREATE OR REPLACE VIEW stg_tse.votacao_candidato_valida AS
SELECT * FROM stg_tse.votacao_candidato_com_destinacao
WHERE universo_destinacao = 'VALIDO';

-- Preserva linhas inválidas no grupo: não removê-las antes de avaliar cobertura.
CREATE OR REPLACE VIEW stg_tse.comparecimento_zonas AS
WITH base AS (
    SELECT stg_tse.inteiro_nao_negativo(s.ano_eleicao) AS ano_eleicao,
           stg_tse.inteiro_nao_negativo(s.cd_eleicao) AS cd_eleicao,
           stg_tse.inteiro_nao_negativo(s.nr_turno) AS nr_turno,
           trim(s.cd_municipio_tse) AS cd_municipio_tse,
           stg_tse.inteiro_nao_negativo(s.nr_zona) AS nr_zona,
           stg_tse.inteiro_nao_negativo(s.qt_aptos) AS aptos,
           stg_tse.inteiro_nao_negativo(s.qt_comparecimento) AS presentes,
           stg_tse.inteiro_nao_negativo(s.qt_abstencao) AS ausentes,
           to_jsonb(s) AS origem
    FROM stg_tse.detalhe_votacao_munzona s
    JOIN stg_tse.escopo_uf uf ON uf.sg_uf = upper(trim(s.sg_uf))
)
SELECT ano_eleicao, cd_eleicao, nr_turno, cd_municipio_tse, nr_zona,
       max(aptos) AS qt_aptos, max(presentes) AS qt_comparecimento,
       max(ausentes) AS qt_abstencao,
       count(DISTINCT (aptos, presentes, ausentes)) AS combinacoes,
       bool_and(aptos IS NOT NULL AND presentes IS NOT NULL
                AND ausentes IS NOT NULL AND aptos::numeric = presentes::numeric + ausentes::numeric
                AND aptos <= 2147483647 AND presentes <= 2147483647
                AND ausentes <= 2147483647) AS medidas_validas,
       jsonb_agg(origem) AS registros_origem
FROM base
GROUP BY ano_eleicao, cd_eleicao, nr_turno, cd_municipio_tse, nr_zona;

CREATE OR REPLACE VIEW stg_tse.comparecimento_cobertura AS
WITH esperadas AS (
    SELECT e.* FROM stg_tse.comparecimento_zonas_esperadas e
    JOIN stg_tse.municipio_correspondencia m USING (cd_municipio_tse)
    JOIN stg_tse.escopo_uf uf ON uf.sg_uf = upper(trim(m.sg_uf))
), confronto AS (
    SELECT coalesce(e.ano_eleicao, z.ano_eleicao) AS ano_eleicao,
           coalesce(e.cd_eleicao, z.cd_eleicao) AS cd_eleicao,
           coalesce(e.nr_turno, z.nr_turno) AS nr_turno,
           coalesce(e.cd_municipio_tse, z.cd_municipio_tse) AS cd_municipio_tse,
           e.nr_zona AS zona_esperada, z.nr_zona AS zona_observada,
           e.manifesto_verificado,
           z.medidas_validas, z.combinacoes,
           z.qt_aptos, z.qt_comparecimento, z.qt_abstencao
    FROM esperadas e FULL JOIN stg_tse.comparecimento_zonas z
      ON e.ano_eleicao = z.ano_eleicao AND e.cd_eleicao = z.cd_eleicao
     AND e.nr_turno = z.nr_turno AND e.cd_municipio_tse = z.cd_municipio_tse
     AND e.nr_zona = z.nr_zona
)
SELECT ano_eleicao, cd_eleicao, nr_turno, cd_municipio_tse,
       count(zona_esperada) AS zonas_esperadas,
       count(zona_observada) AS zonas_observadas,
       bool_and(coalesce(zona_esperada IS NOT NULL AND zona_observada IS NOT NULL
                AND manifesto_verificado AND medidas_validas AND combinacoes = 1, false))
           AND count(zona_esperada) > 0 AS completo,
       sum(qt_aptos::numeric) AS qt_aptos,
       sum(qt_comparecimento::numeric) AS qt_comparecimento,
       sum(qt_abstencao::numeric) AS qt_abstencao
FROM confronto
GROUP BY ano_eleicao, cd_eleicao, nr_turno, cd_municipio_tse;
