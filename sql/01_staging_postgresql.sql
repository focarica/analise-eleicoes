-- Converte valores monetários com vírgula decimal ou ponto decimal. Sentinelas
-- e formatos inesperados resultam em NULL, nunca em zero.
CREATE OR REPLACE FUNCTION stg_tse.parse_brl_amount(valor text)
RETURNS numeric(14,2)
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    v text := trim(valor);
BEGIN
    IF v IS NULL OR upper(v) IN ('', '#NULO', '#NE', '-1', '-3', '-4', 'NÃO DIVULGÁVEL') THEN
        RETURN NULL;
    END IF;
    IF position(',' IN v) > 0 THEN
        v := replace(replace(v, '.', ''), ',', '.');
    END IF;
    IF v !~ '^-?[0-9]+(\.[0-9]{1,2})?$' THEN
        RETURN NULL;
    END IF;
    RETURN v::numeric(14,2);
EXCEPTION WHEN numeric_value_out_of_range OR invalid_text_representation THEN
    RETURN NULL;
END;
$$;

